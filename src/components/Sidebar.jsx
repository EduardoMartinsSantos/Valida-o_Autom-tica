function HomeIcon() {
  return (
    <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor"
      strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      <path d="M3 9.5 12 3l9 6.5V20a1 1 0 0 1-1 1h-5v-6h-6v6H4a1 1 0 0 1-1-1z" />
    </svg>
  )
}

const ITEMS = [
  { id: 'inicio', label: 'Início', Icon: HomeIcon },
  { id: 'configuracoes', label: 'Configurações', Icon: GearIcon, adminOnly: true },
]

function LogoutIcon() {
  return (
    <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor"
      strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4M16 17l5-5-5-5M21 12H9" />
    </svg>
  )
}

export default function Sidebar({ active, onNavigate, user, onLogout }) {
  return (
    <nav className="sidebar" aria-label="Menu principal">
      <div className="sidebar-brand">MOps</div>
      {ITEMS.filter((item) => !item.adminOnly || user.admin).map(({ id, label, Icon }) => (
        <button
          key={id}
          type="button"
          className={`sidebar-item${active === id ? ' active' : ''}`}
          onClick={() => onNavigate(id)}
          title={label}
          aria-label={label}
          aria-current={active === id ? 'page' : undefined}
        >
          <Icon />
        </button>
      ))}
      <button
        type="button"
        className="sidebar-item sidebar-logout"
        onClick={onLogout}
        title={`Sair (${user.name ?? user.email})`}
        aria-label="Sair"
      >
        <LogoutIcon />
      </button>
    </nav>
  )
}
